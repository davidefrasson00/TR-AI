"""
Core Typed Events and Data Models for TR-AI.
Clean, deterministic, typed dataclasses for Market Data, Signals, Orders, and Positions.
"""

from dataclasses import dataclass, field
from datetime import datetime
from enum import Enum
from typing import Dict, List, Optional


class SignalDirection(str, Enum):
    LONG = "LONG"
    SHORT = "SHORT"


class OrderType(str, Enum):
    MARKET = "MARKET"
    LIMIT = "LIMIT"
    STOP = "STOP"


class OrderSide(str, Enum):
    BUY = "BUY"
    SELL = "SELL"


class OrderStatus(str, Enum):
    PENDING = "PENDING"
    APPROVED = "APPROVED"
    REJECTED = "REJECTED"
    FILLED = "FILLED"
    CANCELLED = "CANCELLED"
    EXPIRED = "EXPIRED"


@dataclass(frozen=True)
class Bar:
    """Represents a single completed candlestick."""
    symbol: str
    timeframe: str
    timestamp: datetime  # UTC open time
    open: float
    high: float
    low: float
    close: float
    volume: float = 0.0

    @property
    def range(self) -> float:
        return self.high - self.low

    @property
    def body(self) -> float:
        return abs(self.close - self.open)


@dataclass
class Signal:
    """
    Actionable trade proposal generated by a Strategy.
    Must pass through RiskManager before becoming an Order.
    """
    id: str
    strategy_id: str
    symbol: str
    direction: SignalDirection
    timeframe: str
    entry_price: float
    stop_loss: float
    take_profit_1: float
    take_profit_2: Optional[float] = None
    confidence_score: float = 0.0
    risk_bucket: str = "default"
    rationale: str = ""
    score_breakdown: Dict[str, float] = field(default_factory=dict)
    created_at: datetime = field(default_factory=datetime.utcnow)

    @property
    def stop_distance(self) -> float:
        return abs(self.entry_price - self.stop_loss)

    @property
    def tp1_distance(self) -> float:
        return abs(self.take_profit_1 - self.entry_price)

    @property
    def risk_reward_ratio(self) -> float:
        if self.stop_distance == 0:
            return 0.0
        return self.tp1_distance / self.stop_distance


@dataclass
class Order:
    """
    An execution order validated and sized by RiskManager.
    """
    id: str
    signal_id: str
    symbol: str
    side: OrderSide
    order_type: OrderType
    size_contracts: float
    requested_price: float
    stop_loss: float
    take_profit: float
    take_profit_2: Optional[float] = None
    risk_amount_monetary: float = 0.0
    risk_percentage: float = 0.0
    status: OrderStatus = OrderStatus.PENDING
    rejection_reason: Optional[str] = None
    created_at: datetime = field(default_factory=datetime.utcnow)


@dataclass
class Position:
    """Represents an active open position in the market."""
    id: str
    symbol: str
    side: OrderSide
    size_contracts: float
    entry_price: float
    current_price: float
    stop_loss: float
    take_profit_1: float
    take_profit_2: Optional[float] = None
    risk_amount_monetary: float = 0.0
    risk_bucket: str = "default"
    unrealized_pnl: float = 0.0
    is_partially_closed: bool = False
    is_at_breakeven: bool = False
    opened_at: datetime = field(default_factory=datetime.utcnow)


@dataclass
class AccountInfo:
    """Current state of the broker / simulated trading account."""
    currency: str = "EUR"
    balance: float = 1000.0
    equity: float = 1000.0
    margin_used: float = 0.0
    free_margin: float = 1000.0
    daily_starting_equity: float = 1000.0
    daily_realized_pnl: float = 0.0
    daily_unrealized_pnl: float = 0.0

    @property
    def daily_total_pnl(self) -> float:
        return self.daily_realized_pnl + self.daily_unrealized_pnl

    @property
    def daily_drawdown_pct(self) -> float:
        if self.daily_starting_equity <= 0:
            return 0.0
        loss = max(0.0, -self.daily_total_pnl)
        return (loss / self.daily_starting_equity) * 100.0
